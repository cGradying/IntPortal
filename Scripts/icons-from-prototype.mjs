#!/usr/bin/env node
// Regenerates Views/Pixel/PixelIconGlyphs.swift from the prototype's ICONS
// table, so the native icons stay pixel-identical to the approved design.
// Usage: node Scripts/icons-from-prototype.mjs [prototype.html]
import fs from "node:fs";
import path from "node:path";

const src = process.argv[2] ?? "docs/specs/prototypes/intportal-v3.html";
const out = "Sources/PUPSISPortalApp/Views/Pixel/PixelIconGlyphs.swift";
const html = fs.readFileSync(src, "utf8");
const match = html.match(/const ICONS = (\{[\s\S]*?\n\});/);
if (!match) {
	console.error(`${src}: no ICONS table`);
	process.exit(1);
}
const icons = new Function(`return ${match[1]}`)();
for (const [name, rows] of Object.entries(icons)) {
	if (rows.length !== 12 || rows.some((r) => r.length !== 12 || /[^.#]/.test(r))) {
		console.error(`${name}: not a 12x12 bitmap of . and #`);
		process.exit(1);
	}
}
const cases = Object.entries(icons)
	.map(([name, rows]) => `            case .${name}: [\n${rows.map((r) => `                "${r}",`).join("\n")}\n            ]`)
	.join("\n");
fs.writeFileSync(
	out,
	`// Generated by Scripts/icons-from-prototype.mjs from docs/specs/prototypes/${path.basename(src)}. Do not edit.

extension PixelIcon {
    enum Glyph: String, CaseIterable {
        case ${Object.keys(icons).join(", ")}

        /// 12 rows of 12 cells, \`#\` on.
        var rows: [String] {
            switch self {
${cases}
            }
        }
    }
}
`,
);
console.log(`${out}: ${Object.keys(icons).length} glyphs`);
