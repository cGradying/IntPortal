function inside([x, y], poly) {
  let c = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
}

export const K = 1.55; // world units per degree
export const toWorld = (lon, lat) => [(lon - 122) * K, -(lat - 11.6) * K];

export function mapDots(step = 0.16) {
  const out = [];
  for (let lat = 4.5; lat < 19; lat += step) {
    for (let lon = 116.8; lon < 127; lon += step) {
      if (ISLANDS.some((p) => inside([lon, lat], p))) out.push(toWorld(lon, lat));
    }
  }
  return out;
}

